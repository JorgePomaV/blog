<?php

namespace App\Http\Controllers;
//Clase abstracta: Es una clase que no se puede instanciar directamente, solo se puede heredar
abstract class Controller
{
    /*Funcionalidad compartida: Aquí puedes definir métodos que todos tus controladores necesiten
    Middleware común: Puedes aplicar middleware que afecte a todos los controladores
    Validaciones base: Métodos de validación que se reutilicen en varios controladores
    Helpers comunes: Funciones auxiliares que varios controladores puedan usar*/
}


//En resumen: Es la "plantilla base" que define funcionalidades comunes para todos los controladores de tu aplicación.

